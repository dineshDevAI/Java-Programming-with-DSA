package src.lecture_5.pattern;

public class problem5 {
    public static void main(String[] args) {
        int n =4;
        for(int i=1; i<n-1; i--){
            for(int j=1; j<=n; j++){
                System.out.println("*");
            }
        }
        System.out.println();
        
    }
}
